#!/usr/bin/env python3
"""Generate the export table of a translated module for GetProcAddress.

SRW makes one global symbol for each export: the export name, encoded as
in SymbolName of SRW/SRW_loader.c (tools/importspec.py symbol_name). This
tool reads the export directory of the PE file and writes a C file with
one rt_export_entry for each export, in ordinal order.

The output file contains the export names of the game module. It is a
part of the translated module (in the work directory) and is not
distributed.

Usage: gen_exports.py <pe-file> <table-name> <out.c>
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from importspec import symbol_name  # noqa: E402


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    pe_path, table, out = sys.argv[1:]
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', table):
        sys.stderr.write(f'bad table name {table}\n')
        return 2
    d = open(pe_path, 'rb').read()
    if d[:2] != b'MZ':
        sys.stderr.write('not a PE file\n')
        return 1
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    if d[pe:pe + 4] != b'PE\0\0':
        sys.stderr.write('not a PE file\n')
        return 1
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    opt_size = struct.unpack_from('<H', d, pe + 20)[0]
    opt = pe + 24
    if struct.unpack_from('<H', d, opt)[0] != 0x10B:
        sys.stderr.write('not a 32-bit PE file\n')
        return 1
    secs = []
    for i in range(nsec):
        o = opt + opt_size + 40 * i
        vsize, va, rsize, rptr = struct.unpack_from('<IIII', d, o + 8)
        secs.append((va, max(vsize, rsize), rptr))

    def off(rva):
        for va, size, rptr in secs:
            if va <= rva < va + size:
                return rptr + rva - va
        raise ValueError(f'rva 0x{rva:x} is not in a section')

    exp_rva, exp_size = struct.unpack_from('<II', d, opt + 96)
    entries = []
    if exp_rva != 0:
        e = off(exp_rva)
        base, nfunc, nname, afunc, aname, aord = struct.unpack_from('<IIIIII', d, e + 16)
        names = {}
        for i in range(nname):
            nrva = struct.unpack_from('<I', d, off(aname) + 4 * i)[0]
            idx = struct.unpack_from('<H', d, off(aord) + 2 * i)[0]
            s = d[off(nrva):].split(b'\0', 1)[0].decode('latin-1')
            names[idx] = s
        for idx in range(nfunc):
            frva = struct.unpack_from('<I', d, off(afunc) + 4 * idx)[0]
            if frva == 0:
                continue
            if exp_rva <= frva < exp_rva + exp_size:
                sys.stderr.write(f'forwarded export at ordinal {base + idx} is not supported\n')
                return 1
            if idx not in names:
                sys.stderr.write(f'export without a name at ordinal {base + idx} is not supported\n')
                return 1
            entries.append((base + idx, names[idx], symbol_name(names[idx])))

    with open(out, 'w', encoding='ascii') as f:
        f.write(f'/* Generated by tools/gen_exports.py from {os.path.basename(pe_path)}, do not edit. */\n')
        f.write('#include "rt_module.h"\n\n')
        for _, _, sym in entries:
            f.write(f'extern char {sym}[];\n')
        f.write(f'\nconst rt_export_entry {table}[] = {{\n')
        for ordinal, name, sym in entries:
            if '"' in name or '\\' in name:
                raise ValueError(f'export name {name} cannot be written as a C string')
            f.write(f'    {{ "{name}", {ordinal}, {sym} }},\n')
        f.write('};\n')
        f.write(f'const unsigned {table}_count = {len(entries)};\n')
    print(f'{len(entries)} exports')
    return 0


if __name__ == '__main__':
    sys.exit(main())
