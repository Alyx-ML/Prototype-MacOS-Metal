#!/usr/bin/env python3
"""Generate the COM method thunks and vtables from runtime/com.spec.

Output:
  runtime/llasm/com_thunks.llasm  one llasm procedure com_<vtable>_<method>_asm2c
                                  per vtable entry. The procedure calls the C
                                  function, removes the argument dwords and
                                  returns to the guest.
  runtime/include/rt_com_thunks.h prototypes of the C functions and the
                                  declarations of the vtables rt_vt_<vtable>.
  runtime/src/rt_com_vtables.c    the vtable descriptions (thunk addresses)
                                  and the functions of unsupported methods.

Usage: gen_com_thunks.py <com.spec> <com_thunks.llasm> <rt_com_thunks.h> <rt_com_vtables.c>
"""
import re
import sys

IDENT = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')


class Method:
    def __init__(self, name, dwords, cname, unsupported):
        self.name = name
        self.dwords = dwords
        self.cname = cname
        self.unsupported = unsupported


class Vtable:
    def __init__(self, name, interface, line):
        self.name = name
        self.interface = interface
        self.line = line
        self.methods = []


def read_spec(path):
    vtables = []
    names = set()
    with open(path, encoding='ascii') as f:
        for n, raw in enumerate(f, 1):
            line = raw.split('#', 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if parts[0] == 'vtable':
                if len(parts) != 3 or not all(IDENT.fullmatch(p) for p in parts[1:]):
                    raise ValueError(f'{path}:{n}: expected "vtable <name> <interface>"')
                if parts[1] in names:
                    raise ValueError(f'{path}:{n}: duplicate vtable {parts[1]}')
                names.add(parts[1])
                vtables.append(Vtable(parts[1], parts[2], n))
                continue
            if not vtables:
                raise ValueError(f'{path}:{n}: method before the first vtable line')
            if len(parts) not in (2, 3) or not IDENT.fullmatch(parts[0]) or not parts[1].isdigit():
                raise ValueError(f'{path}:{n}: expected "<method> <stack-dwords> [<c-name> | -]"')
            vt = vtables[-1]
            dwords = int(parts[1])
            if dwords < 1:
                raise ValueError(f'{path}:{n}: a COM method has at least the this pointer')
            if any(m.name == parts[0] for m in vt.methods):
                raise ValueError(f'{path}:{n}: duplicate method {parts[0]} in {vt.name}')
            unsupported = len(parts) == 3 and parts[2] == '-'
            if len(parts) == 3 and not unsupported:
                if not IDENT.fullmatch(parts[2]):
                    raise ValueError(f'{path}:{n}: bad C name {parts[2]}')
                cname = parts[2]
            else:
                cname = f'rt_com_{vt.name}_{parts[0]}'
            vt.methods.append(Method(parts[0], dwords, cname, unsupported))
    for vt in vtables:
        if len(vt.methods) < 3:
            raise ValueError(f'{path}:{vt.line}: vtable {vt.name} has no IUnknown methods')
    return vtables


def thunk_name(vt, m):
    return f'com_{vt.name}_{m.name}_asm2c'


def main() -> int:
    if len(sys.argv) != 5:
        sys.stderr.write(__doc__)
        return 2
    spec, out_llasm, out_h, out_c = sys.argv[1:]
    vtables = read_spec(spec)

    cfuncs = {}
    for vt in vtables:
        for m in vt.methods:
            prev = cfuncs.get(m.cname)
            if prev is not None and prev != m.dwords:
                raise ValueError(f'{spec}: {m.cname} is used with {prev} and {m.dwords} stack dwords')
            cfuncs[m.cname] = m.dwords

    with open(out_llasm, 'w', encoding='ascii') as f:
        f.write(';; Generated by tools/gen_com_thunks.py from runtime/com.spec, do not edit.\n')
        f.write(';; Each thunk is the native target of one guest COM vtable entry.\n\n')
        f.write('include llasm.llinc\n\n')
        for cname in sorted(cfuncs):
            f.write(f'funcv {cname} $\n')
        f.write('\n')
        for vt in vtables:
            for m in vt.methods:
                f.write(f'proc {thunk_name(vt, m)} public\n')
                f.write(f'; {vt.interface}::{m.name}\n')
                f.write(f'        call {m.cname} $\n')
                f.write('        load tmp0, esp, 4\n')
                f.write(f'        add esp, esp, {4 + 4 * m.dwords}\n')
                f.write('        tcall tmp0\n')
                f.write('endp\n\n')

    with open(out_h, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_com_thunks.py from runtime/com.spec, do not edit. */\n')
        f.write('#ifndef RT_COM_THUNKS_H\n#define RT_COM_THUNKS_H\n\n#include "rt_com.h"\n\n')
        for cname in sorted(cfuncs):
            f.write(f'void {cname}(_cpu *cpu); /* {cfuncs[cname]} stack dwords */\n')
        f.write('\n')
        for vt in vtables:
            f.write(f'extern rt_com_vtable rt_vt_{vt.name}; /* {vt.interface}, {len(vt.methods)} methods */\n')
        f.write('\n#endif\n')

    with open(out_c, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_com_thunks.py from runtime/com.spec, do not edit. */\n')
        f.write('#include "rt_com_thunks.h"\n\n')
        for vt in vtables:
            for m in vt.methods:
                f.write(f'extern char {thunk_name(vt, m)}[];\n')
        f.write('\n/* Methods that the runtime does not support. */\n')
        done = set()
        for vt in vtables:
            for m in vt.methods:
                if m.unsupported and m.cname not in done:
                    done.add(m.cname)
                    f.write(f'void {m.cname}(_cpu *cpu)\n{{\n    (void)cpu;\n')
                    f.write(f'    rt_fatal("COM method {vt.interface}::{m.name} is not supported by the runtime");\n}}\n\n')
        for vt in vtables:
            f.write(f'static char *const thunks_{vt.name}[] = {{\n')
            for m in vt.methods:
                f.write(f'    {thunk_name(vt, m)},\n')
            f.write('};\n')
            f.write(f'rt_com_vtable rt_vt_{vt.name} = {{ "{vt.interface}", {len(vt.methods)}u, thunks_{vt.name}, 0 }};\n\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
