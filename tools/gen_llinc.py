#!/usr/bin/env python3
"""Generate an llasm .llinc declaration file from the exported helper
prototypes in a preprocessed llasm-support C file.

Usage: gen_llinc.py <preprocessed.i> <output.llinc>
"""
import re
import sys

PROTO = re.compile(r'\b(void|uint32_t)\s+((?:sse|x86|x87)_[a-z0-9_]+)\s*\(\s*_cpu\s*\*\s*cpu\s*((?:,[^)]*)?)\)\s*\{')


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    with open(sys.argv[1], encoding='utf-8') as f:
        text = f.read()
    seen = {}
    for ret, name, rest in PROTO.findall(text):
        params = []
        for p in [x.strip() for x in rest.split(',') if x.strip()]:
            parts = p.split()
            if len(parts) != 2 or parts[0] not in ('uint32_t', 'int'):
                sys.stderr.write(f'error: unsupported parameter "{p}" in {name}\n')
                return 1
            params.append(parts[1])
        kind = 'funcv' if ret == 'void' else 'func'
        line = kind + ' ' + name + ' $' + ''.join(', ' + p for p in params)
        if name in seen and seen[name] != line:
            sys.stderr.write(f'error: conflicting prototypes for {name}\n')
            return 1
        seen[name] = line
    with open(sys.argv[2], 'w', encoding='utf-8') as f:
        f.write(';part of the macOS ARM64 port -- generated by tools/gen_llinc.py from llasm_x86ext.c, do not edit\n\n')
        for name in sorted(seen):
            f.write(seen[name] + '\n')
    print(f'{len(seen)} declarations')
    return 0


if __name__ == '__main__':
    sys.exit(main())
