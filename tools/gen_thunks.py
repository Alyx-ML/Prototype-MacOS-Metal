#!/usr/bin/env python3
"""Generate the import thunks from runtime/imports.spec.

Output:
  runtime/llasm/thunks.llasm   one llasm procedure <sym>_asm2c per function
                               import. The procedure calls the C function
                               and returns to the guest.
  runtime/include/rt_imports.h prototypes of the C functions.
  runtime/src/rt_import_table.c
                               table of all imports (DLL, name or ordinal,
                               guest-visible address) for GetProcAddress on
                               system DLLs.

Usage: gen_thunks.py <imports.spec> <thunks.llasm> <rt_imports.h> <rt_import_table.c>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from importspec import read_spec  # noqa: E402


def main() -> int:
    if len(sys.argv) != 5:
        sys.stderr.write(__doc__)
        return 2
    spec, out_llasm, out_h, out_table = sys.argv[1:]
    entries = read_spec(spec)
    funcs = [e for e in sorted(entries.values(), key=lambda e: e.sym) if e.kind != 'data']

    with open(out_llasm, 'w', encoding='ascii') as f:
        f.write(';; Generated by tools/gen_thunks.py from runtime/imports.spec, do not edit.\n')
        f.write(';; Each thunk is the native target of one guest import.\n\n')
        f.write('include llasm.llinc\n\n')
        for e in funcs:
            if e.kind in ('std', 'unreachable'):
                f.write(f'funcv {e.cname} $\n')
            else:
                f.write(f'func {e.cname} $\n')
        f.write('\n')
        for e in funcs:
            f.write(f'proc {e.thunk} public\n')
            f.write(f'; {e.dll} {e.name}\n')
            if e.kind in ('std', 'unreachable'):
                f.write(f'        call {e.cname} $\n')
                f.write('        load tmp0, esp, 4\n')
                f.write(f'        add esp, esp, {4 + 4 * e.dwords}\n')
                f.write('        tcall tmp0\n')
            else:
                f.write(f'        call {e.cname} $\n')
                f.write('        tcall tmp0\n')
            f.write('endp\n\n')

    with open(out_h, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_thunks.py from runtime/imports.spec, do not edit. */\n')
        f.write('#ifndef RT_IMPORTS_H\n#define RT_IMPORTS_H\n\n#include "llasm_cpu.h"\n\n')
        for e in sorted(entries.values(), key=lambda e: e.sym):
            if e.kind == 'std':
                f.write(f'void {e.cname}(_cpu *cpu); /* {e.dll} {e.name}, {e.dwords} stack dwords */\n')
            elif e.kind == 'unreachable':
                f.write(f'void {e.cname}(_cpu *cpu); /* {e.dll} {e.name}: not called by translated code */\n')
            elif e.kind == 'jump':
                f.write(f'uint32_t {e.cname}(_cpu *cpu); /* {e.dll} {e.name} */\n')
        f.write('\n/* Data imports: the runtime defines these objects. */\n')
        for e in sorted(entries.values(), key=lambda e: e.sym):
            if e.kind == 'data':
                f.write(f'/* {e.dll} {e.name}: symbol {e.thunk} */\n')
        f.write('\n#endif\n')

    with open(out_table, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/gen_thunks.py from runtime/imports.spec, do not edit. */\n')
        f.write('#include "rt_module.h"\n\n')
        all_entries = sorted(entries.values(), key=lambda e: (e.dll, e.sym))
        for e in all_entries:
            f.write(f'extern char {e.thunk}[];\n')
        f.write('\nconst rt_import_entry rt_import_table[] = {\n')
        for e in all_entries:
            m = re.fullmatch(r'ord_' + re.escape(e.dll) + r'_([0-9]+)', e.name)
            if m:
                f.write(f'    {{ "{e.dll}", NULL, {int(m.group(1))}, {e.thunk} }},\n')
            else:
                if '"' in e.name or '\\' in e.name:
                    raise ValueError(f'import name {e.name} cannot be written as a C string')
                f.write(f'    {{ "{e.dll}", "{e.name}", 0, {e.thunk} }},\n')
        f.write('};\n')
        f.write(f'const unsigned rt_import_table_count = {len(all_entries)};\n')
        unreachable = [e for e in all_entries if e.kind == 'unreachable']
        if unreachable:
            f.write('\n/* Imports that no translated code calls (kind "unreachable"). */\n')
        for e in unreachable:
            f.write(f'void {e.cname}(_cpu *cpu);\n')
            f.write(f'void {e.cname}(_cpu *cpu)\n{{\n    (void)cpu;\n')
            f.write(f'    rt_fatal("{e.dll} {e.name} was called, but no translated code calls it (dead code only)");\n}}\n')
    print(f'{len(funcs)} thunks, {len(entries) - len(funcs)} data imports')
    return 0


if __name__ == '__main__':
    sys.exit(main())
